"""AccessCaster - READ-ONLY compatibility probe for the RODECaster Duo.

The whole app was reverse-engineered against the Pro II. This script does NOT
write a single byte of device state. It only:

  1. Enumerates the RODE HID interfaces and shows which one we'd talk to.
  2. Runs the three documented read-only commands (VER / info / ping).
  3. Replays the app-free "dump full device model" trigger (report-3 ad10a7b0)
     and parses the returned property stream to learn the Duo's shape:
       - firmware / model / any identifying strings,
       - how many input channels it exposes (mic gain / phantom / type counts),
       - MIDI-control state,
       - the full list of property NAMES the Duo reports (for a later RE pass).

Every command here is one the Pro II answered read-only; none change settings.
Run it with the RODE Central app CLOSED (it grabs the HID interface).

Usage (from anywhere):
    python DevTools/duo_probe.py
Writes a human-readable report to ProjectMemory/DUO_PROBE_RESULT.md and prints
the same to stdout.
"""
from __future__ import annotations

import os
import re
import sys
from collections import Counter

# Make the Project modules importable no matter where we're launched from, and locate the notes,
# which live in a private sibling repo rather than in this one.
_HERE = os.path.dirname(os.path.abspath(__file__))
if _HERE not in sys.path:
    sys.path.insert(0, _HERE)
import _bootstrap  # noqa: E402,F401  (puts Project/ on sys.path)

import rcp_hid  # noqa: E402
import rcp_read  # noqa: E402


# Property names we care about for a shape read. All read-only lookups.
_COUNT_PROPS = [
    "inputMicrophoneGain",   # one per mic input -> mic count
    "inputPower",            # one per input that supports 48V
    "inputPhaseFlip",        # one per input
    "inputMicrophoneType",   # one per mic input
    "inputDigitalGain",      # one per line/digital input
    "channelInputSource",    # fader vector size
    "mixDisabled",           # matrix cell count -> output x source shape
]
_SCALAR_PROPS = [
    "systemFirmwareVersion",
    "systemMidiControl",
    "systemHardwareVersion",
    "systemSerialNumber",
    "systemProductName",
    "systemModelName",
    "productName",
    "modelName",
    "deviceName",
    "systemDeviceName",
]

# A property name in the stream is an ASCII token that ends right before its
# value header. Grab lowercase-starting camelCase-ish tokens for discovery.
_NAME_RE = re.compile(rb"[a-z][A-Za-z0-9]{3,40}")


def _distinct_property_names(blob: bytes) -> list[tuple[str, int]]:
    """Best-effort list of (name, occurrences) for property-like tokens whose
    following bytes look like one of our known value headers. Discovery only."""
    counts: Counter = Counter()
    for m in _NAME_RE.finditer(blob):
        name = m.group()
        tail = blob[m.end():m.end() + 3]
        # value block starts with optional 0x00 then 0x01 <len> <type>
        if tail[:1] == b"\x00":
            tail = blob[m.end() + 1:m.end() + 4]
        if tail[:1] == b"\x01":
            counts[name.decode("latin1")] += 1
    return sorted(counts.items(), key=lambda kv: (-kv[1], kv[0]))


def _ascii_strings(blob: bytes, minlen: int = 4) -> list[str]:
    """Printable-ASCII runs, for spotting a model/firmware string by eye."""
    out, cur = [], []
    for b in blob:
        if 32 <= b < 127:
            cur.append(chr(b))
        else:
            if len(cur) >= minlen:
                out.append("".join(cur))
            cur = []
    if len(cur) >= minlen:
        out.append("".join(cur))
    return out


def main() -> int:
    lines: list[str] = []

    def emit(s: str = "") -> None:
        print(s)
        lines.append(s)

    emit("# RODECaster Duo - read-only probe result")
    emit("")
    emit("Generated by DevTools/duo_probe.py. No device state was written.")
    emit("")

    # --- 1. interfaces ----------------------------------------------------
    emit("## 1. RODE HID interfaces enumerated")
    emit("")
    ifaces = rcp_hid.enumerate_interfaces()
    if not ifaces:
        emit("  (none) - no RODE vendor HID interface found. Is the Duo on and connected?")
    for i in ifaces:
        emit(f"  - {i.describe()}  serial={i.serial_number!r}  control={i.is_control}")
    emit("")

    control = rcp_hid.find_control_interface()
    if control is None:
        emit("## RESULT: no vendor control interface (usage page 0xFF00) found.")
        emit("The app would fail to connect. Stopping (nothing else to read).")
        _write(lines)
        return 1
    emit(f"Control interface we would use: {control.describe()}")
    emit(f"(Pro II used PID 0x0037 / MI_09. This Duo reports PID 0x{control.product_id:04x} "
         f"/ MI_{control.interface_number:02d}.)")
    emit("")

    # --- 2. documented read-only commands ---------------------------------
    emit("## 2. Documented read-only commands (VER / info / ping)")
    emit("")
    try:
        with rcp_hid.RodeCaster.open_path(control) as dev:
            ver = dev.get_version()
            emit(f"  get_version() : {ver!r}")
            info = dev.get_info()
            emit(f"  get_info()    : {info[:32].hex()} ... ({len(info)} bytes)")
            emit(f"  ping()        : {dev.ping()}")
    except Exception as exc:
        emit(f"  ERROR opening/reading control interface: {exc}")
    emit("")

    # --- 3. full property model dump (app-free read) ----------------------
    emit("## 3. Property model dump (report-3 ad10a7b0, read-only)")
    emit("")
    try:
        blob = rcp_read.read_model()
    except Exception as exc:
        emit(f"  ERROR reading model: {exc}")
        _write(lines)
        return 1
    emit(f"  model stream bytes: {len(blob)}")
    if not blob:
        emit("  Empty stream - the Duo did not answer the dump trigger the way the Pro II does.")
        emit("  (Connect/commands may still work; the model-dump format may differ.)")
        _write(lines)
        return 0
    emit("")

    # scalar identifiers
    emit("### Identifying / scalar properties")
    for name in _SCALAR_PROPS:
        vals = rcp_read.find_all(blob, name)
        if vals:
            emit(f"  {name} : {vals[0][0]!r}  ({vals[0][1]})")
    emit("")

    # channel-shape counts (this is the big Pro-II-vs-Duo question)
    emit("### Channel-shape counts (Pro II shown for comparison)")
    proii = {"inputMicrophoneGain": 4, "inputPower": 4, "inputPhaseFlip": 9,
             "inputMicrophoneType": 4, "channelInputSource": 9, "mixDisabled": 516}
    for name in _COUNT_PROPS:
        vals = rcp_read.find_all(blob, name)
        cmp = f"  (Pro II: {proii[name]})" if name in proii else ""
        emit(f"  {name:22} count={len(vals)}{cmp}")
        if name in ("inputMicrophoneGain", "inputPower", "inputMicrophoneType") and vals:
            emit(f"      values: {[v for v, k in vals]}")
    emit("")

    # discovery: every property name the Duo reports
    names = _distinct_property_names(blob)
    emit(f"### All property names reported by the Duo ({len(names)} distinct)")
    emit("")
    for name, n in names:
        emit(f"  {name} (x{n})")
    emit("")

    # raw strings, useful for spotting a model name we didn't guess
    strings = _ascii_strings(blob, minlen=5)
    interesting = [s for s in strings if re.search(r"(?i)duo|rodecaster|rode|v?\d+\.\d+", s)]
    emit("### Notable ASCII strings in the stream (model / version hints)")
    emit("")
    for s in dict.fromkeys(interesting):  # dedupe, keep order
        emit(f"  {s!r}")
    emit("")

    emit("## Interpretation notes")
    emit("- Connect works if a control interface was found and VER/ping answered.")
    emit("- If channel-shape counts differ from the Pro II, Pro II selectors "
         "(0x6E-0x71 etc.) target the WRONG parameter on the Duo. Do NOT write.")
    emit("- The property-name list is the starting point for a Duo profile.")

    _write(lines)
    return 0


def _write(lines: list[str]) -> None:
    out_path = _bootstrap.notes_path("ProjectMemory", "DUO_PROBE_RESULT.md")
    try:
        with open(out_path, "w", encoding="utf-8") as f:
            f.write("\n".join(lines) + "\n")
        print(f"\n[report written to {out_path}]")
    except Exception as exc:
        print(f"\n[could not write report: {exc}]")


if __name__ == "__main__":
    raise SystemExit(main())
