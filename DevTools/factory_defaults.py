"""Every value a desk holds straight after a factory reset, safe to publish.

    python DevTools/factory_defaults.py --blob captures/post-reset-raw.bin --desk PRO2 \
        --taken "29th August 2026"

Writes docs/FACTORY_DEFAULTS_<DESK>.txt from a saved model dump. The dump must be taken at the
setup wizard straight after a factory reset, before anything is touched, or the file describes that
desk's state rather than the factory's.

Two kinds of value are withheld. Secrets (`_redact`): a factory reset keeps the wifi network and its
password, so the dump still carries them. And values that differ from one unit to the next, such as
a show's id or the recordings already on the drive, which say nothing about the factory state.

READ-ONLY: it reads a file and writes one; it never touches the desk.
"""
from __future__ import annotations

import argparse
import pathlib
import re

import _bootstrap  # puts Project/ on the path, and finds docs/; import FIRST
import rcp_read
from _redact import REDACTED, redact

# Values that belong to this unit, its account or its drive rather than to the factory state.
PER_UNIT = re.compile(r"uuid|recordingcontent|renewal|address|mac", re.IGNORECASE)
PER_UNIT_TEXT = "<differs per unit>"


def _text(value, kind: str) -> str:
    if kind == "bytes":
        return repr(value)
    if kind == "str":
        try:
            value = value.encode("latin-1").decode("utf-8")   # the parser hands UTF-8 over as latin-1
        except (UnicodeEncodeError, UnicodeDecodeError):
            pass
        return f'"{value}"'
    if isinstance(value, float):
        return f"{value:.6g}"
    return str(value)


def _shown(name: str, value, kind: str) -> str:
    if redact(name, value) == REDACTED:
        return REDACTED
    if PER_UNIT.search(name):
        return PER_UNIT_TEXT
    return _text(value, kind)


def _runs(values: list) -> str:
    """Every instance's value in order, a run of equal values written once with its count."""
    out = []
    for v in values:
        if out and out[-1][0] == v:
            out[-1][1] += 1
        else:
            out.append([v, 1])
    return ", ".join(v if n == 1 else f"{v} (x{n})" for v, n in out)


def collect(blob: bytes) -> dict:
    """{block: {name: [shown value per instance]}}, both in stream order."""
    blocks: dict = {}
    for block, name, value, kind in rcp_read.iter_block_properties(blob):
        blocks.setdefault(block or "?", {}).setdefault(name, []).append(_shown(name, value, kind))
    return blocks


def render(blocks: dict, desk_name: str, firmware: str, taken: str) -> str:
    total = sum(len(v) for names in blocks.values() for v in names.values())
    L = [f"FACTORY DEFAULTS: EVERY VALUE A {desk_name.upper()} HOLDS AFTER A FACTORY RESET",
         "",
         f"Read from a {desk_name} on firmware {firmware}, at the setup wizard straight after a "
         f"factory reset, on {taken}.",
         f"{total} values in {sum(len(n) for n in blocks.values())} properties across "
         f"{len(blocks)} blocks. Generated by DevTools/factory_defaults.py; do not edit by hand.",
         "",
         "Each block lists its properties in the order the desk sends them. A property the desk",
         "holds once shows its value; one it holds per channel, pad or slot shows every instance in",
         'order, with a run of equal values written once and counted: "0 (x8)" is eight zeros.',
         "Text values are in double quotes. Meter, fader and pot values are the live hardware at",
         "that moment, not settings.",
         "",
         f"{REDACTED}: a password, account name or network name, which a factory reset keeps.",
         f"{PER_UNIT_TEXT}: an id, address or recording list that belongs to this unit.",
         "",
         "A later firmware adds properties and can change defaults, so check the firmware above",
         "before relying on a value.",
         ""]
    for block, names in blocks.items():
        L.append("")
        L.append(block)
        for name, values in names.items():
            L.append(f"  {name} = {_runs(values)}")
    return "\n".join(L) + "\n"


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("--blob", required=True, help="a model dump taken straight after a reset")
    ap.add_argument("--desk", required=True, choices=["PRO2", "DUO"])
    ap.add_argument("--taken", required=True, help='when the dump was taken, "29th August 2026"')
    args = ap.parse_args()
    blob = pathlib.Path(args.blob).read_bytes()
    firmware = rcp_read.block_value(blob, "SYSTEM", "systemFirmwareVersion") or "unknown"
    desk_name = {"PRO2": "RODECaster Pro II", "DUO": "RODECaster Duo"}[args.desk]
    out = pathlib.Path(_bootstrap.docs_path(f"FACTORY_DEFAULTS_{args.desk}.txt"))
    out.write_text(render(collect(blob), desk_name, firmware, args.taken), encoding="utf-8")
    print(f"wrote {out}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
